-- 审核只能从活动轮次决定一次，并校验非自审和驳回、撤回身份。
CREATE FUNCTION protect_answer_card_review() RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'answer card review is retained';
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF OLD.state <> 'IN_REVIEW' OR NEW.state = 'IN_REVIEW'
            OR (NEW.id, NEW.card_id, NEW.branch_id, NEW.revision_id, NEW.round_no, NEW.submitted_by, NEW.submitted_at)
                IS DISTINCT FROM (OLD.id, OLD.card_id, OLD.branch_id, OLD.revision_id, OLD.round_no, OLD.submitted_by, OLD.submitted_at)
            OR NEW.review_version <> OLD.review_version + 1 THEN
            RAISE EXCEPTION 'answer card review transition is invalid';
        END IF;
    ELSIF NEW.state <> 'IN_REVIEW' OR NEW.review_version <> 0 THEN
        RAISE EXCEPTION 'answer card review must start pending';
    END IF;
    IF NEW.state IN ('APPROVED', 'REJECTED') AND
        (NEW.decided_by = NEW.submitted_by OR EXISTS (
            SELECT 1 FROM kb_answer_card_contributor WHERE branch_id = NEW.branch_id AND user_id = NEW.decided_by)) THEN
        RAISE EXCEPTION 'answer card self review is forbidden';
    END IF;
    IF NEW.state = 'WITHDRAWN' AND NEW.decided_by <> NEW.submitted_by THEN
        RAISE EXCEPTION 'answer card withdrawal owner mismatch';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_answer_card_review_protection BEFORE INSERT OR UPDATE OR DELETE ON kb_answer_card_review
    FOR EACH ROW EXECUTE FUNCTION protect_answer_card_review();

-- 延迟到事务结束校验发布证据及草稿指针，避免通过只更新卡片指针绕过审核。
CREATE FUNCTION validate_answer_card_publication() RETURNS TRIGGER AS $$
DECLARE
    current_card kb_answer_card%ROWTYPE;
BEGIN
    SELECT * INTO current_card FROM kb_answer_card WHERE id = NEW.id;
    IF current_card.published_revision_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM kb_answer_card_review ar
        JOIN kb_answer_card_revision r ON r.id = ar.revision_id AND r.card_id = ar.card_id
        JOIN kb_answer_card_stewardship st ON st.card_id = r.card_id
        WHERE ar.card_id = current_card.id AND ar.revision_id = current_card.published_revision_id
          AND ar.state = 'APPROVED' AND char_length(btrim(r.answer)) > 0 AND char_length(btrim(r.applicability_text)) > 0
          AND (SELECT count(*) FROM kb_answer_card_source WHERE revision_id = r.id) BETWEEN 1 AND 10
    ) THEN
        RAISE EXCEPTION 'answer card publication evidence is missing';
    END IF;
    IF current_card.active_branch_id IS NOT NULL AND NOT EXISTS (
        SELECT 1 FROM kb_answer_card_branch WHERE id = current_card.active_branch_id
            AND card_id = current_card.id AND NOT closed AND latest_revision_id IS NOT NULL
    ) THEN
        RAISE EXCEPTION 'answer card draft pointer is invalid';
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;
CREATE CONSTRAINT TRIGGER trg_answer_card_publication AFTER INSERT OR UPDATE ON kb_answer_card
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_answer_card_publication();

-- 固定空间和单调发布指针不能被后续写入撤销；所有业务历史保留。
CREATE FUNCTION protect_answer_card_identity() RETURNS TRIGGER AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'answer card identity is retained';
    END IF;
    IF NEW.id <> OLD.id OR NEW.space_id <> OLD.space_id OR NEW.created_at <> OLD.created_at
        OR NEW.card_version <> OLD.card_version + 1 THEN
        RAISE EXCEPTION 'answer card identity or version mismatch';
    END IF;
    IF OLD.published_revision_id IS NOT NULL AND
        (NEW.published_revision_id IS NULL OR NEW.published_revision_id < OLD.published_revision_id) THEN
        RAISE EXCEPTION 'answer card publication cannot move backwards';
    END IF;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;
CREATE TRIGGER trg_answer_card_identity BEFORE UPDATE OR DELETE ON kb_answer_card
    FOR EACH ROW EXECUTE FUNCTION protect_answer_card_identity();

