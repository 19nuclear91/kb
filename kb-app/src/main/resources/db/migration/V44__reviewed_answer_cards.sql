-- 标准答案卡首期：独立内容修订、人工审核、固定来源、责任人复审及幂等回执。
-- 仅创建新业务结构及一次性功能权限；不把文档或私人会话转换为答案卡。

-- 稳定卡片引用空间，任何草稿或历史都阻止空间被级联删除。
CREATE TABLE kb_answer_card (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id BIGINT NOT NULL REFERENCES kb_space(id) ON DELETE RESTRICT,
    card_version BIGINT NOT NULL DEFAULT 0 CHECK (card_version >= 0),
    published_revision_id BIGINT,
    active_branch_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
COMMENT ON TABLE kb_answer_card IS '标准答案卡稳定身份与当前发布、草稿指针';
COMMENT ON COLUMN kb_answer_card.id IS '答案卡稳定标识';
COMMENT ON COLUMN kb_answer_card.space_id IS '关联知识空间，创建后固定';
COMMENT ON COLUMN kb_answer_card.card_version IS '并发版本，初始0，每次成功写入递增';
COMMENT ON COLUMN kb_answer_card.published_revision_id IS '当前已批准内容修订，未发布为空';
COMMENT ON COLUMN kb_answer_card.active_branch_id IS '活动草稿分支，无草稿为空';
COMMENT ON COLUMN kb_answer_card.created_at IS '创建时间，带时区';

-- 分支允许发布版与待修改内容并存，每卡只允许一个活动分支。
CREATE TABLE kb_answer_card_branch (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id BIGINT NOT NULL REFERENCES kb_answer_card(id),
    branch_no BIGINT NOT NULL CHECK (branch_no > 0),
    latest_revision_id BIGINT,
    closed BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (id, card_id),
    UNIQUE (card_id, branch_no)
);
CREATE UNIQUE INDEX uq_answer_card_active_branch ON kb_answer_card_branch(card_id) WHERE NOT closed;
COMMENT ON TABLE kb_answer_card_branch IS '标准答案卡草稿分支及最新修订';
COMMENT ON COLUMN kb_answer_card_branch.id IS '草稿分支标识';
COMMENT ON COLUMN kb_answer_card_branch.card_id IS '所属答案卡标识';
COMMENT ON COLUMN kb_answer_card_branch.branch_no IS '卡片内分支序号，从1递增';
COMMENT ON COLUMN kb_answer_card_branch.latest_revision_id IS '分支最新内容修订标识';
COMMENT ON COLUMN kb_answer_card_branch.closed IS 'true为批准后关闭，false为活动草稿或审核中';

-- 每次保存追加修订；文本索引字段与原文同事务产生，不引用文件分块。
CREATE TABLE kb_answer_card_revision (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    card_id BIGINT NOT NULL REFERENCES kb_answer_card(id),
    branch_id BIGINT NOT NULL,
    revision_no BIGINT NOT NULL CHECK (revision_no > 0),
    question TEXT NOT NULL CHECK (char_length(question) BETWEEN 1 AND 256),
    aliases_json JSONB NOT NULL CHECK (jsonb_typeof(aliases_json) = 'array' AND jsonb_array_length(aliases_json) <= 20),
    answer TEXT NOT NULL CHECK (char_length(answer) <= 16000),
    applicability_text TEXT NOT NULL CHECK (char_length(applicability_text) <= 2000),
    effective_from DATE,
    until_kind TEXT NOT NULL CHECK (until_kind IN ('UNDECLARED', 'OPEN_ENDED', 'DATE')),
    effective_until DATE,
    normalized_questions_json JSONB NOT NULL CHECK (jsonb_typeof(normalized_questions_json) = 'array' AND jsonb_array_length(normalized_questions_json) BETWEEN 1 AND 21),
    question_text TEXT NOT NULL,
    created_by BIGINT NOT NULL REFERENCES sys_user(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (id, card_id),
    UNIQUE (id, branch_id, card_id),
    UNIQUE (card_id, revision_no),
    FOREIGN KEY (branch_id, card_id) REFERENCES kb_answer_card_branch(id, card_id),
    CHECK ((until_kind = 'DATE') = (effective_until IS NOT NULL)),
    CHECK (effective_from IS NULL OR effective_from BETWEEN DATE '1900-01-01' AND DATE '2999-12-31'),
    CHECK (effective_until IS NULL OR effective_until BETWEEN DATE '1900-01-01' AND DATE '2999-12-31'),
    CHECK (effective_from IS NULL OR effective_until IS NULL OR effective_from <= effective_until)
);
